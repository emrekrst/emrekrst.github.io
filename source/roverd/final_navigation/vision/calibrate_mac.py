# calibrate_mac.py - Capture marker patterns using Mac webcam
# Saves patterns to config_mac.py

import re
import cv2
import sys
sys.path.append('.')

from square_finder import find_squares
from pattern_reader import warp_to_patch, extract_grid


def capture_grid_live():
    """Show live preview, press SPACE to capture, ESC to cancel."""
    cap = cv2.VideoCapture(0)
    if not cap.isOpened():
        print("ERROR: Cannot open camera")
        return None

    print("  Opening camera preview... Press SPACE to capture, ESC to cancel")

    captured_grid = None

    while True:
        ok, frame = cap.read()
        if not ok:
            break

        vis = frame.copy()
        gray = cv2.cvtColor(frame, cv2.COLOR_BGR2GRAY)
        markers = find_squares(gray=gray)

        if markers:
            best = max(markers, key=lambda m: m['area'])
            corners = best['corners'].astype(int)

            # Draw green outline on detected square
            cv2.polylines(vis, [corners.reshape(-1, 1, 2)], True, (0, 255, 0), 2)

            # Show grid preview
            patch = warp_to_patch(frame, best['corners'])
            grid = extract_grid(patch)

            # Draw grid values on screen
            cv2.putText(vis, f"Grid: {grid[0].tolist()}", (10, vis.shape[0] - 100),
                       cv2.FONT_HERSHEY_SIMPLEX, 0.5, (0, 255, 0), 1)
            cv2.putText(vis, f"      {grid[1].tolist()}", (10, vis.shape[0] - 75),
                       cv2.FONT_HERSHEY_SIMPLEX, 0.5, (0, 255, 0), 1)
            cv2.putText(vis, f"      {grid[2].tolist()}", (10, vis.shape[0] - 50),
                       cv2.FONT_HERSHEY_SIMPLEX, 0.5, (0, 255, 0), 1)
            cv2.putText(vis, f"      {grid[3].tolist()}", (10, vis.shape[0] - 25),
                       cv2.FONT_HERSHEY_SIMPLEX, 0.5, (0, 255, 0), 1)

            cv2.putText(vis, "Press SPACE to capture", (10, 30),
                       cv2.FONT_HERSHEY_SIMPLEX, 0.7, (0, 255, 0), 2)
        else:
            cv2.putText(vis, "No marker detected", (10, 30),
                       cv2.FONT_HERSHEY_SIMPLEX, 0.7, (0, 0, 255), 2)

        cv2.imshow("Calibrate - Hold marker steady", vis)

        # Longer waitKey for better key detection
        key = cv2.waitKey(30) & 0xFF
        if key == ord(' ') or key == 13:  # Space OR Enter to capture
            if markers:
                captured_grid = grid.tolist()
                print("  Captured!")
                break
            else:
                print("  No marker detected, can't capture")
        elif key == 27:  # ESC to cancel
            print("  Cancelled")
            break

    cap.release()
    cv2.destroyAllWindows()
    return captured_grid


def fmt_row(row):
    return '[' + ','.join(str(v) for v in row) + ']'


def save_to_config_mac(patterns):
    """Save patterns to config_mac.py"""
    n = len(list(patterns.values())[0])

    lines = []
    lines.append(f'# config_mac.py - Mac webcam calibrated patterns\n')
    lines.append(f'# Generated by calibrate_mac.py\n\n')
    lines.append(f'# ===== MARKER PATTERNS ({n}x{n} grid: 1=black, 0=white) =====\n')
    lines.append('PATTERNS_MAC = {\n')

    items = list(patterns.items())
    for i, (name, grid) in enumerate(items):
        comma = ',' if i < len(items) - 1 else ''
        lines.append(f"    '{name}': [{fmt_row(grid[0])},\n")
        for row in grid[1:-1]:
            lines.append(f"             {fmt_row(row)},\n")
        lines.append(f"             {fmt_row(grid[-1])}]{comma}\n")
        if i < len(items) - 1:
            lines.append('\n')
    lines.append('}\n')

    with open('config_mac.py', 'w') as f:
        f.writelines(lines)


captured = {}

print("=" * 40)
print("MAC WEBCAM PATTERN CALIBRATOR")
print("=" * 40)

for marker in ['left', 'right']:
    while True:
        print(f"\n=== Capture {marker.upper()} marker ===")
        grid = capture_grid_live()
        if grid is None:
            print("  Cancelled or no detection. Try again.")
            continue
        print(f"  Captured grid:")
        for row in grid:
            print(f"    {row}")
        confirm = input("  Save this pattern? (y/n): ").strip().lower()
        if confirm == 'y':
            captured[marker] = grid
            print(f"  {marker.upper()} saved.\n")
            break

save_to_config_mac(captured)
print("\nDone! Saved to config_mac.py")
print(f"  left:  {captured['left']}")
print(f"  right: {captured['right']}")
